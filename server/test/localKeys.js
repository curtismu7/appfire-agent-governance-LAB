const b64u = (buf) => Buffer.from(buf).toString('base64url');
const EC_SCALAR = createHash('sha256').update('appfire local tool server test curve point (public, protects nothing)').digest();
const ecdh = createECDH('prime256v1');
ecdh.setPrivateKey(EC_SCALAR);
const point = ecdh.getPublicKey(); // 0x04 | X | Y
export const EC_A_JWK = { kty: 'EC', crv: 'P-256', x: b64u(point.subarray(1, 33)), y: b64u(point.subarray(33, 65)), d: b64u(EC_SCALAR) };

// A second EC curve point is not needed. The public half of a JWK is the same object without its private members.
const PRIVATE = ['d', 'p', 'q', 'dp', 'dq', 'qi'];
export const publicOf = (jwk) => Object.fromEntries(Object.entries(jwk).filter(([k]) => !PRIVATE.includes(k)));
